/**
 * Builds the dotted world map behind What Is My IP's location card.
 *
 *   npm pack world-atlas@2.0.2 && tar xzf world-atlas-2.0.2.tgz
 *   node scripts/build-world-dots.mjs package/land-110m.json > tools/what-is-my-ip/core/world-dots.ts
 *
 * The land outline is Natural Earth's (public domain), as packaged by
 * world-atlas (ISC). Every cell of a 2° grid with land anywhere among nine
 * sample points becomes a dot, so narrow land (Malaya, Japan, New Zealand)
 * survives; each row is stored as runs of consecutive land cells, which
 * the page draws as dotted lines — a few kilobytes instead of a tile server
 * that would learn where the visitor is.
 */
import { readFileSync } from 'node:fs'
import process from 'node:process'

const STEP = 2
const NORTH = 83
const SOUTH = -57

const topology = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const [sx, sy] = topology.transform.scale
const [tx, ty] = topology.transform.translate

// Decode the delta-encoded, quantised arcs into longitude/latitude points.
const arcs = topology.arcs.map((arc) => {
  let x = 0
  let y = 0
  return arc.map(([dx, dy]) => {
    x += dx
    y += dy
    return [x * sx + tx, y * sy + ty]
  })
})

function ring(indexes) {
  const points = []
  for (const index of indexes) {
    const arc = index < 0 ? [...arcs[~index]].reverse() : arcs[index]
    points.push(...(points.length ? arc.slice(1) : arc))
  }
  // A ring that crosses the antimeridian (Chukotka, Fiji) jumps 360° in one
  // edge, which would paint its whole row as land. Unwrap it into one
  // continuous shape; points are then tested at x and x ± 360.
  let shift = 0
  return points.map(([x, y], i) => {
    if (i > 0) {
      const previous = points[i - 1][0]
      if (x - previous > 180)
        shift -= 360
      else if (previous - x > 180)
        shift += 360
    }
    return [x + shift, y]
  })
}

const polygons = []
for (const geometry of topology.objects.land.geometries) {
  const list = geometry.type === 'Polygon' ? [geometry.arcs] : geometry.arcs
  for (const polygon of list)
    polygons.push(polygon.map(ring))
}

function inRing(x, y, points) {
  let inside = false
  for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
    const [xi, yi] = points[i]
    const [xj, yj] = points[j]
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi)
      inside = !inside
  }
  return inside
}

// Even-odd across a polygon's rings handles holes (the Caspian, the great lakes).
const inPolygon = (x, y, rings) => rings.reduce((inside, points) => inside !== inRing(x, y, points), false)
const isLand = (x, y) => polygons.some(rings => [x, x - 360, x + 360].some(lon => inPolygon(lon, y, rings)))

const OFFSETS = [-STEP / 3, 0, STEP / 3]
const hasLand = (x, y) => OFFSETS.some(dx => OFFSETS.some(dy => isLand(x + dx, y + dy)))

const rows = []
for (let lat = NORTH; lat >= SOUTH; lat -= STEP) {
  const runs = []
  let start = -1
  const cols = 360 / STEP
  for (let col = 0; col <= cols; col++) {
    const land = col < cols && hasLand(-180 + (col + 0.5) * STEP, lat)
    if (land && start < 0)
      start = col
    if (!land && start >= 0) {
      runs.push(start, col - start)
      start = -1
    }
  }
  rows.push(runs)
}

process.stdout.write(`/*
 * Generated by scripts/build-world-dots.mjs from Natural Earth's land outline
 * (public domain, via world-atlas). Do not edit by hand.
 */

/** Degrees between dots, and the latitude of the first and last rows. */
export const WORLD_STEP = ${STEP}
export const WORLD_NORTH = ${NORTH}
export const WORLD_SOUTH = ${SOUTH}

/** One entry per row, north to south: pairs of [first column, length] of land. */
export const WORLD_ROWS: readonly (readonly number[])[] = [
${rows.map(runs => `  [${runs.join(', ')}],`).join('\n')}
]
`)
